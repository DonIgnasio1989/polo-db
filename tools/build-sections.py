# ================================================================= сборка ====
def build():
    path = os.path.join(ROOT, 'data', 'sections.json')
    with open(path, encoding='utf-8') as f:
        s = json.load(f)

    # --- Torque: полная замена набора строк
    s['Torque']['cols'] = TORQUE_COLS
    s['Torque']['rows'] = TORQUE_ROWS

    # --- Diagnostics: правка расшифровок + добавление + 5-я колонка
    d = s['Diagnostics']
    d['cols'] = ['Код', 'Значение', 'Симптомы / причина', 'Что делать', 'Детали каталога']
    by_code = {r[0]: i for i, r in enumerate(d['rows']) if r and r[0]}
    for code, row in DTC_FIX.items():
        if code in by_code:
            d['rows'][by_code[code]] = row
        else:
            d['rows'].append(row)
    have = set(by_code) | set(DTC_FIX)
    for row in DTC_NEW:
        if row[0] not in have:
            d['rows'].append(row)
            have.add(row[0])
    # служебные строки-примечания — в конец, без дублей
    existing_notes = {tuple(r[:2]) for r in d['rows']}
    for row in DTC_NOTES:
        if tuple(row[:2]) not in existing_notes:
            d['rows'].append(row)
    # коды — по возрастанию, примечания (—) остаются в конце
    codes = [r for r in d['rows'] if r[0] != '—']
    notes = [r for r in d['rows'] if r[0] == '—']
    codes.sort(key=lambda r: r[0])

    # приводим каждую строку к 5 колонкам: симптомы в 3-ю, ссылки в 5-ю
    def enrich(r):
        r = list(r)
        while len(r) < 5:
            r.append('')
        code = r[0]
        sym = DTC_SYMPTOMS.get(code, '')
        if sym and not r[2].startswith(sym.rstrip()):
            r[2] = (sym + r[2]).strip()
        # 5-ю колонку ВСЕГДА пересчитываем из DTC_PARTS: иначе правки маппинга
        # не попадали бы в файл (строка уже содержала старое значение)
        links = DTC_PARTS.get(code, [])
        r[4] = ';;'.join('%s|#q:%s' % (lbl, q) for lbl, q in links)
        # симптомы — то же: источник истины DTC_SYMPTOMS, а не прошлая сборка
        return r[:5]

    codes = [enrich(r) for r in codes]
    notes = [(r + [''] * 5)[:5] for r in notes]
    d['rows'] = codes + notes

    # --- остальные разделы: дописать строки, не повторяя существующие
    def append(sid, rows, key=lambda r: tuple(r)):
        sec = s[sid]
        seen = {key(r) for r in sec['rows']}
        for r in rows:
            if key(r) not in seen:
                sec['rows'].append(r)
                seen.add(key(r))
    append('WiringRef', WIRING_REF_NEW, key=lambda r: r[0])
    append('WiringFuses', FUSES_NEW, key=lambda r: tuple(r))
    append('WiringRelays', RELAYS_NEW, key=lambda r: tuple(r))
    append('WiringPins', PINS_NEW, key=lambda r: (r[0], r[1]))
    append('Wiring', WIRING_NEW, key=lambda r: r[0][:40])

    # --- Wheels: размеры шин и давления берём ИЗ каталога (нет расхождений)
    parts_path = os.path.join(ROOT, 'data', 'parts.json')
    tire_rows = []
    if os.path.exists(parts_path):
        with open(parts_path, encoding='utf-8') as f:
            parts = json.load(f)
        import re as _re
        for r in parts:
            oem = str(r.get('o') or r.get('oem') or '').strip()
            if not _re.match(r'^\d{3}/\d{2} R\d{2}$', oem):
                continue
            # пары (код, текст): s — спецификация, n — заметка, w — предупреждение
            inst = [(x[0], x[1]) for x in (r.get('i') or [])
                    if isinstance(x, list) and len(x) == 2 and isinstance(x[1], str)]
            spec = next((t for c, t in inst if c == 's'), '')
            press = [t for c, t in inst if c in ('n', 'w') and ('загрузка' in t or 'бар' in t.lower())]
            val = spec or ''
            if press:
                val += (' · ' if val else '') + ' '.join(p.replace('• ', '').strip() for p in press)
            note = ''
            if 'индекс нагрузки' not in val.lower():
                note = '⚠ в карточке нет индексов нагрузки/скорости и вылета диска — сверить по наклейке на стойке двери'
            # сортировка: диаметр, затем ширина, затем профиль
            w_, prof, dia = _re.match(r'^(\d{3})/(\d{2}) R(\d{2})$', oem).groups()
            tire_rows.append([oem, str(r.get('n') or r.get('name') or ''),
                              (val or '—') + ((' — ' + note) if note else ''),
                              (int(dia), int(w_), int(prof))])
    tire_rows.sort(key=lambda x: x[3])
    tire_rows = [x[:3] for x in tire_rows]
    if 'Wheels' not in s:
        s['Wheels'] = {'icon': '🛞', 'label': 'Колёса и шины', 'cols': WHEELS_COLS, 'rows': []}
    s['Wheels']['cols'] = WHEELS_COLS
    s['Wheels']['rows'] = (WHEELS_STATIC
                           + [['РАЗМЕРЫ ШИН И ДАВЛЕНИЯ (собрано из карточек каталога)', '', '']]
                           + tire_rows
                           + [['Поколения и размеры', '13″ — преимущественно 6N1 (1994–1999), 14–15″ — 6N2 (1999–2001)',
                               '⚠ Ориентир, а не правило: на ранних 6N2 встречались и 13″. Точный размер — по наклейке на стойке двери водителя или в нише запаски, а также по PR-кодам оснащения']]
                           + [WHEELS_NOTE])

    # --- новые разделы
    if 'Lamps' not in s:
        s['Lamps'] = {'icon': '💡', 'label': 'Лампы и цоколи', 'cols': LAMPS_COLS, 'rows': LAMPS_ROWS}
    else:
        s['Lamps']['cols'], s['Lamps']['rows'] = LAMPS_COLS, LAMPS_ROWS
    if 'FluidSpecs' not in s:
        s['FluidSpecs'] = {'icon': '🛢️', 'label': 'Жидкости и объёмы', 'cols': FLUID_COLS, 'rows': FLUID_ROWS}
    else:
        s['FluidSpecs']['cols'], s['FluidSpecs']['rows'] = FLUID_COLS, FLUID_ROWS

    # порядок разделов в файле — как в сайдбаре (CAT_GROUPS.refs)
    order = ['Torque', 'Diagnostics', 'Lamps', 'FluidSpecs', 'Wheels', 'Wiring',
             'WiringFuses', 'WiringRelays', 'WiringRef', 'WiringPins']
    ordered = {k: s[k] for k in order if k in s}
    for k in s:
        if k not in ordered:
            ordered[k] = s[k]
    return ordered

